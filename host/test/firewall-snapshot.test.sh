#!/usr/bin/env sh
# firewall-snapshot.test.sh: offline harness for the read-only firewall snapshot. Puts
# mock ufw, iptables-save, ip6tables-save, nft, fail2ban-client, sysctl, systemctl, ss
# and hostname on PATH and asserts:
#   - the sections come in their order, with the listeners section last
#   - the very last line of the output is the HOSTSEC_LISTEN_ALLOW line for check 12
#     (non-loopback listeners only, sorted), as the script's header says
#   - rule counters and nftables set elements are stripped, so two runs on an unchanged
#     box print the same text
#
#   sh host/test/firewall-snapshot.test.sh
#
# Exit 0 = all asserts passed. Needs bash (the script is a bash script).
set -u

HERE=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd -P)
SCRIPT="$HERE/../firewall-snapshot.sh"
[ -f "$SCRIPT" ] || { echo "cannot find $SCRIPT"; exit 2; }
command -v bash >/dev/null 2>&1 || { echo "SKIP: no bash on PATH"; exit 0; }

WORK=$(mktemp -d 2>/dev/null || echo "${TMPDIR:-/tmp}/fst.$$"); mkdir -p "$WORK"
BIN="$WORK/bin"; mkdir -p "$BIN"

mock() {  # name  (body on stdin)
  { echo '#!/bin/sh'; cat; } > "$BIN/$1"; chmod +x "$BIN/$1"
}
mock hostname <<'EOF'
echo web1
EOF
mock ufw <<'EOF'
echo "Status: active"
echo "To                         Action      From"
echo "22/tcp                     ALLOW IN    Anywhere"
EOF
mock iptables-save <<'EOF'
echo "# Generated by iptables-save v0.0 on a day"
echo "*filter"
echo ":INPUT ACCEPT [1234:567890]"
echo ":DOCKER - [0:0]"
echo "-A INPUT -p tcp --dport 22 -j ACCEPT"
echo "COMMIT"
EOF
mock ip6tables-save <<'EOF'
echo "*filter"
echo ":INPUT DROP [9:99]"
echo "COMMIT"
EOF
# nft: two tables beside the iptables view; the fail2ban-like one has a set whose
# elements (banned addresses) change every minute.
mock nft <<'EOF'
case "$*" in
  "list tables") printf 'table ip filter\ntable inet f2b-table\ntable inet nethersec_flood\n' ;;
  "-s list table inet f2b-table")
    printf 'table inet f2b-table {\n\tset addr-set-sshd {\n\t\ttype ipv4_addr\n\t\telements = { 203.0.113.5, 203.0.113.6,\n\t\t\t     198.51.100.7 }\n\t}\n}\n' ;;
  "-s list table inet nethersec_flood")
    printf 'table inet nethersec_flood {\n\tset flood_drop {\n\t\ttype ipv4_addr\n\t\tflags timeout\n\t}\n}\n' ;;
  *) echo "unexpected nft call: $*" >&2; exit 1 ;;
esac
EOF
mock fail2ban-client <<'EOF'
printf 'Status\n|- Number of jail:\t1\n`- Jail list:\tsshd\n'
EOF
mock sysctl <<'EOF'
echo 0
EOF
mock systemctl <<'EOF'
case "$1" in is-enabled) echo enabled ;; is-active) echo active ;; esac
EOF
# ss -Htuln[p]: one public TCP and one public UDP listener, plus loopback ones that the
# allowlist must leave out.
mock ss <<'EOF'
printf '%s\n' \
  'udp UNCONN 0 0 [::]:443 [::]:* users:(("caddy",pid=3,fd=7))' \
  'tcp LISTEN 0 4096 0.0.0.0:22 0.0.0.0:* users:(("sshd",pid=1,fd=3))' \
  'tcp LISTEN 0 4096 127.0.0.1:5432 0.0.0.0:* users:(("postgres",pid=2,fd=3))' \
  'tcp LISTEN 0 4096 [::1]:8125 [::]:* users:(("statsd",pid=4,fd=6))'
EOF

PASS=0; FAIL=0; CUR=""
ok()  { PASS=$((PASS+1)); }
bad() { FAIL=$((FAIL+1)); echo "  FAIL [$CUR]: $1"; }
t()   { CUR="$1"; }
runit() { env PATH="$BIN:$PATH" bash "$SCRIPT" > "$1" 2>"$WORK/stderr"; RC=$?; }

t "runs"
runit "$WORK/out1"
[ "$RC" = 0 ] && ok || bad "expected exit 0, got $RC"
[ -s "$WORK/out1" ] && ok || bad "no output"

# 1. the last line is the allowlist line, with only the non-loopback listeners, sorted
t "allowlist-is-the-last-line"
last=$(tail -n 1 "$WORK/out1")
[ "$last" = 'HOSTSEC_LISTEN_ALLOW="tcp/0.0.0.0:22 udp/[::]:443"' ] && ok \
  || bad "the last line must be the allowlist (got: $last)"
[ "$(grep -c '^HOSTSEC_LISTEN_ALLOW=' "$WORK/out1")" = 1 ] && ok || bad "exactly one allowlist line"

# 2. the sections in order, the listeners last (the units section above them)
t "section-order"
got=$(sed -n 's/^## //p' "$WORK/out1" | tr '\n' '|')
want="ufw|iptables-save (IPv4)|ip6tables-save (IPv6)|nftables tables|fail2ban jails|sysctls|systemd firewall units|listening on a non-loopback address|"
[ "$got" = "$want" ] && ok || bad "section order (got: $got)"
grep -q '^ufw.service: enabled / active$' "$WORK/out1" && ok || bad "the units section must list each unit"
# the listeners section holds the two public sockets and then the allowlist line, nothing else
sect=$(sed -n '/^## listening on a non-loopback address$/,$p' "$WORK/out1" | sed '1d')
[ "$sect" = "$(printf '%s\n%s\n%s' 'tcp 0.0.0.0:22 sshd' 'udp [::]:443 caddy' 'HOSTSEC_LISTEN_ALLOW="tcp/0.0.0.0:22 udp/[::]:443"')" ] && ok \
  || bad "the listeners section (got: $(printf '%s' "$sect" | tr '\n' '|'))"

# 3. counters and set elements are stripped; the iptables view's tables are not repeated
t "stripped-and-stable"
grep -q '^:INPUT ACCEPT$' "$WORK/out1" && ok || bad "iptables counters must be stripped"
grep -q '^# Generated' "$WORK/out1" && bad "iptables-save's comment line must be dropped" || ok
grep -qF 'elements = { (stripped) }' "$WORK/out1" && ok || bad "set elements must be replaced by (stripped)"
grep -q '203\.0\.113\.5\|198\.51\.100\.7' "$WORK/out1" && bad "a banned address leaked into the snapshot" || ok
grep -q '^### table ip filter$' "$WORK/out1" && bad "the ip filter table is the iptables view, not repeated" || ok
grep -q '^### table inet nethersec_flood$' "$WORK/out1" && ok || bad "other nftables tables must be listed"
runit "$WORK/out2"
cmp -s "$WORK/out1" "$WORK/out2" && ok || bad "two runs on an unchanged box must print the same text"

# 4. the header's claim matches: it says the allowlist is the last line
t "header-says-last-line"
sed -n '2,/^set -uo pipefail/p' "$SCRIPT" | tr '\n' ' ' | grep -q 'last line of the output is' && ok \
  || bad "the header must say the allowlist is the last line of the output"

echo ""
echo "firewall-snapshot: $PASS passed, $FAIL failed"
rm -rf "$WORK" 2>/dev/null || :
[ "$FAIL" -eq 0 ]
